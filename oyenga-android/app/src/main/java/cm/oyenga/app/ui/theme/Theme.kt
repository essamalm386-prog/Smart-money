/**
 * Thème de l'application.
 *
 * Le mode sombre n'est pas une variante décorative : les deux schémas viennent du même
 * algorithme HCT, avec les contrastes garantis par construction. Suivre la préférence
 * système est le comportement par défaut, comme dans le kit.
 */
@Composable
fun OyengaTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    val colorScheme = if (darkTheme) DarkScheme else LightScheme
    val view = LocalView.current

    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            WindowCompat.getInsetsController(window, view).apply {
                isAppearanceLightStatusBars = !darkTheme
                isAppearanceLightNavigationBars = !darkTheme
            }
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = OyengaTypography,
        shapes = OyengaMaterialShapes,
        content = content,
    )
}
